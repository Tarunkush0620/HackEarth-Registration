const norm = (s) => String(s || '').toLowerCase().replace(/[^a-z0-9]/g, '');

function lookupTeam(inputTeamName, inputLeaderName = '') {
  const cleanInput = String(inputTeamName || '').trim();
  const inputKey = norm(cleanInput);
  if (!inputKey) return null;

  // 1. Exact case-insensitive match
  let matches = ROSTER.filter(t => t.team_name.toLowerCase().trim() === cleanInput.toLowerCase());

  // 2. Normalized match (ignoring spaces, punctuation, special chars)
  if (matches.length === 0) {
    matches = ROSTER.filter(t => norm(t.team_name) === inputKey);
  }

  // 3. Disambiguate duplicate team names using team leader name
  if (matches.length > 1 && inputLeaderName) {
    const leaderKey = norm(inputLeaderName);
    const byLeader = matches.find(t => {
      const tLeaderKey = norm(t.team_leader);
      return leaderKey.includes(tLeaderKey) || tLeaderKey.includes(leaderKey);
    });
    if (byLeader) return byLeader;
  }
  if (matches.length > 0) return matches[0];

  // 4. Flexible match for "Team <Name>" prefix vs "<Name>"
  const strippedInput = inputKey.replace(/^team/, '');
  matches = ROSTER.filter(t => {
    const tKey = norm(t.team_name).replace(/^team/, '');
    return tKey === strippedInput || (strippedInput.length >= 3 && (tKey.startsWith(strippedInput) || strippedInput.startsWith(tKey)));
  });

  if (matches.length > 1 && inputLeaderName) {
    const leaderKey = norm(inputLeaderName);
    const byLeader = matches.find(t => {
      const tLeaderKey = norm(t.team_leader);
      return leaderKey.includes(tLeaderKey) || tLeaderKey.includes(leaderKey);
    });
    if (byLeader) return byLeader;
  }

  return matches.length > 0 ? matches[0] : null;
}

function resolveTeam(teamName, leaderName = '', fallbackNumber = 167) {
  const matched = lookupTeam(teamName, leaderName);
  if (matched) {
    return {
      teamNumber: matched.team_number,
      teamId: matched.team_id,
      panel: matched.panel,
      officialTeamName: matched.team_name,
      officialLeader: matched.team_leader,
      matched: true,
    };
  }
  const num = Number(fallbackNumber) || 167;
  return {
    teamNumber: num,
    teamId: String(num).padStart(3, '0'),
    panel: null,
    officialTeamName: teamName,
    officialLeader: leaderName,
    matched: false,
  };
}

